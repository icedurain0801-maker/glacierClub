CREATE TABLE `po_contents` (
  `id` char(36) COLLATE utf8mb4_unicode_ci NOT NULL,
  `game_id` char(36) COLLATE utf8mb4_unicode_ci NOT NULL,
  `source_id` char(36) COLLATE utf8mb4_unicode_ci NOT NULL,
  `external_id` varchar(255) COLLATE utf8mb4_unicode_ci NOT NULL,
  `content_type` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL,
  `author_name` varchar(160) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `title` text COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `body` mediumtext COLLATE utf8mb4_unicode_ci NOT NULL,
  `media` longtext CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL CHECK (json_valid(`media`)),
  `published_at` datetime DEFAULT NULL,
  `source_url` text COLLATE utf8mb4_unicode_ci NOT NULL,
  `engagement` longtext CHARACTER SET utf8mb4 COLLATE utf8mb4_bin NOT NULL CHECK (json_valid(`engagement`)),
  `fingerprint` char(64) COLLATE utf8mb4_unicode_ci NOT NULL,
  `collected_at` datetime NOT NULL DEFAULT current_timestamp(),
  `account_id` char(36) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `platform_author_id` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `root_content_id` char(36) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `parent_content_id` char(36) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `platform_parent_id` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  `content_depth` tinyint(4) NOT NULL DEFAULT 0,
  `is_deleted` tinyint(1) NOT NULL DEFAULT 0,
  `raw_payload` longtext CHARACTER SET utf8mb4 COLLATE utf8mb4_bin DEFAULT NULL CHECK (json_valid(`raw_payload`)),
  `first_seen_at` datetime DEFAULT NULL,
  `last_seen_at` datetime DEFAULT NULL,
  `community_id` char(36) COLLATE utf8mb4_unicode_ci DEFAULT NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `po_contents_source_external_uk` (`source_id`,`external_id`),
  KEY `po_contents_game_time_idx` (`game_id`,`published_at`),
  KEY `po_contents_source_time_idx` (`source_id`,`published_at`),
  KEY `po_contents_account_time_idx` (`account_id`,`published_at`),
  KEY `po_contents_root_idx` (`root_content_id`,`parent_content_id`),
  KEY `po_contents_parent_fk` (`parent_content_id`),
  KEY `po_contents_parent_root_idx` (`root_content_id`,`parent_content_id`),
  KEY `po_contents_published_time_idx` (`published_at`,`id`),
  KEY `po_contents_community_time_idx` (`community_id`,`published_at`),
  KEY `po_contents_game_collected_idx` (`game_id`,`collected_at`,`is_deleted`),
  KEY `po_contents_source_collected_idx` (`source_id`,`collected_at`,`is_deleted`),
  CONSTRAINT `po_contents_account_fk` FOREIGN KEY (`account_id`) REFERENCES `po_accounts` (`id`) ON DELETE SET NULL,
  CONSTRAINT `po_contents_community_fk` FOREIGN KEY (`community_id`) REFERENCES `po_communities` (`id`),
  CONSTRAINT `po_contents_game_fk` FOREIGN KEY (`game_id`) REFERENCES `po_games` (`id`),
  CONSTRAINT `po_contents_parent_fk` FOREIGN KEY (`parent_content_id`) REFERENCES `po_contents` (`id`) ON DELETE SET NULL,
  CONSTRAINT `po_contents_root_fk` FOREIGN KEY (`root_content_id`) REFERENCES `po_contents` (`id`) ON DELETE SET NULL,
  CONSTRAINT `po_contents_source_fk` FOREIGN KEY (`source_id`) REFERENCES `po_sources` (`id`),
  CONSTRAINT `po_contents_type_chk` CHECK (`content_type` in ('post','comment','video','review'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci